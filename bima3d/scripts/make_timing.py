#!/usr/bin/env python3
"""Build src/videos/bima/timing.ts from voice/words.json + segment layout.
Segment layout must match how voice.wav was concatenated (see concat_voice.sh):
segments in order s1..s8 with GAP seconds of silence between them.
"""
import json, subprocess, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30
GAP = 0.15
SEGS = [f"s{i}" for i in range(1, 9)]

def dur(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                   "-of", "csv=p=0", path]).decode().strip()
    return float(out)

bounds = {}
t = 0.0
for i, s in enumerate(SEGS):
    d = dur(os.path.join(ROOT, "voice", "proc", f"{s}t.wav"))
    bounds[s] = (t, t + d)
    t += d + (GAP if i < len(SEGS) - 1 else 0.0)
total = t

words = json.load(open(os.path.join(ROOT, "voice", "words.json")))["words"]
W = [{"w": w["word"], "start": w["start"], "end": w["end"]} for w in words]
# Replace ASR spellings with the true script words, aligned via difflib on normalized tokens.
import difflib
script_words = []
for s in SEGS:
    for tok in open(os.path.join(ROOT, "voice", f"{s}.txt")).read().split():
        parts = tok.split("-")
        if len(parts) > 1:  # "kira-kira" -> ["kira-", "kira"] to match ASR token splits
            script_words += [parts[0] + "-"] + parts[1:]
        else:
            script_words.append(tok)
norm = lambda x: x.lower().strip('.,!?":;"\u201d')
sm = difflib.SequenceMatcher(a=[norm(w["w"]) for w in W], b=[norm(x) for x in script_words], autojunk=False)
aligned = [None] * len(script_words)
for tag, i1, i2, j1, j2 in sm.get_opcodes():
    if i2 > i1:
        t0, t1 = W[i1]["start"], W[i2 - 1]["end"]
    else:
        t0 = t1 = (W[i1]["start"] if i1 < len(W) else (W[-1]["end"] if W else 0.0))
    n = j2 - j1
    for k in range(n):
        a = t0 + (t1 - t0) * (k / n); b = t0 + (t1 - t0) * ((k + 1) / n)
        aligned[j1 + k] = {"w": script_words[j1 + k], "start": a, "end": b}
assert all(x is not None for x in aligned)
W = aligned
print(f"captions: {len(W)} script words aligned onto ASR timings")

# caption phrases: 2-4 words, break on sentence punctuation or pause > 0.4 s
phrases = []
cur = []
def flush():
    global cur
    if cur:
        phrases.append({
            "text": " ".join(x["w"] for x in cur).replace("- ", "-"),
            "a": round(cur[0]["start"] * FPS), "b": round(cur[-1]["end"] * FPS) + 5,
        })
        cur = []
for i, w in enumerate(W):
    cur.append(w)
    endp = w["w"].rstrip('"”').endswith((".", "!", "?", "…", "..."))
    pause = (W[i + 1]["start"] - w["end"] > 0.4) if i + 1 < len(W) else True
    if len(cur) >= 4 or endp or (pause and len(cur) >= 2):
        flush()
flush()

# merge 1-word phrases into the next phrase when the result stays <= 4 words
merged = []
for ph in phrases:
    if merged and len(merged[-1]["text"].split()) == 1 and len(merged[-1]["text"].split()) + len(ph["text"].split()) <= 4:
        merged[-1]["text"] = (merged[-1]["text"] + " " + ph["text"]).replace("- ", "-")
        merged[-1]["b"] = ph["b"]
    else:
        merged.append(ph)
phrases = merged

seg_js = ",\n  ".join(f'{s}: {{ a: {round(bounds[s][0]*FPS)}, b: {round(bounds[s][1]*FPS)} }}' for s in SEGS)
words_js = ",\n  ".join(
    f'{{ w: {json.dumps(w["w"], ensure_ascii=False)}, start: {round(w["start"]*FPS)}, end: {round(w["end"]*FPS)} }}' for w in W)
cap_js = ",\n  ".join(
    f'{{ text: {json.dumps(p["text"], ensure_ascii=False)}, a: {p["a"]}, b: {p["b"]} }}' for p in phrases)

out = f"""// GENERATED by scripts/make_timing.py from voice/words.json — do not edit by hand.
export const FPS = {FPS};
export interface SegRange {{ a: number; b: number }}
export const SEG: Record<string, SegRange> = {{
  {seg_js},
}};
export const TOTAL_FRAMES = {round(total * FPS)};
export interface Word {{ w: string; start: number; end: number }}
export const WORDS: Word[] = [
  {words_js}
];
export interface Phrase {{ text: string; a: number; b: number }}
export const CAPTIONS: Phrase[] = [
  {cap_js}
];
"""
open(os.path.join(ROOT, "src", "videos", "bima", "timing.ts"), "w").write(out)
print(f"total {total:.2f}s = {round(total*FPS)} frames; words {len(W)}; phrases {len(phrases)}")
for s in SEGS:
    print(s, f"{bounds[s][0]:.2f}..{bounds[s][1]:.2f}")
